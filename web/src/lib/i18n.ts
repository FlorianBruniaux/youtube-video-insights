export function resolveLanguage(
  storedLanguage: string | null,
  browserLanguages: readonly string[],
): Language {
  if (storedLanguage === "en" || storedLanguage === "fr") return storedLanguage;
  return browserLanguages.some((language) => language.toLowerCase().startsWith("fr"))
    ? "fr"
    : "en";
}

export function currentLanguage(root: HTMLElement = document.documentElement): Language {
  return root.dataset.language === "fr" ? "fr" : "en";
}

export function translate(
  english: string,
  language: Language = currentLanguage(),
  values: Readonly<Record<string, string | number>> = {},
): string {
  const template = language === "fr" ? (FRENCH_TRANSLATIONS[english] ?? english) : english;
  return template.replace(/\{([a-z_]+)\}/g, (match, key: string) => {
    const value = values[key];
    return value === undefined ? match : String(value);
  });
}

export function applyLanguage(language: Language, root: ParentNode = document): void {
  document.documentElement.lang = language;
  document.documentElement.dataset.language = language;
  for (const element of root.querySelectorAll<HTMLElement>("[data-i18n]")) {
    const english = element.dataset.i18n;
    if (english !== undefined) element.textContent = translate(english, language);
  }
  for (const input of root.querySelectorAll<HTMLInputElement | HTMLTextAreaElement>(
    "[data-i18n-placeholder]",
  )) {
    const english = input.dataset.i18nPlaceholder;
    if (english !== undefined) input.placeholder = translate(english, language);
  }
  for (const element of root.querySelectorAll<HTMLElement>("[data-i18n-aria-label]")) {
    const english = element.dataset.i18nAriaLabel;
    if (english !== undefined) element.setAttribute("aria-label", translate(english, language));
  }
  for (const element of root.querySelectorAll<HTMLMetaElement>("[data-i18n-content]")) {
    const english = element.dataset.i18nContent;
    if (english !== undefined) element.content = translate(english, language);
  }
  const titleSource = root.querySelector<HTMLElement>("[data-i18n-document-title]")
    ?.dataset.i18nDocumentTitle;
  if (titleSource !== undefined) {
    const localizedTitle = translate(titleSource, language);
    document.title = localizedTitle === "YT Insights"
      ? localizedTitle
      : `${localizedTitle} | YT Insights`;
  }
  updateLanguageControls(root, language);
}

export function installLanguageControls(
  root: ParentNode = document,
  storage: Storage = window.localStorage,
  reload: () => void = () => window.location.reload(),
): () => void {
  const controller = new AbortController();
  for (const button of root.querySelectorAll<HTMLButtonElement>("[data-language-option]")) {
    button.addEventListener(
      "click",
      () => {
        const language = button.dataset.languageOption;
        if (language !== "en" && language !== "fr") return;
        try {
          storage.setItem(LANGUAGE_STORAGE_KEY, language);
        } catch {
          return;
        }
        reload();
      },
      { signal: controller.signal },
    );
  }
  return () => controller.abort();
}

function updateLanguageControls(root: ParentNode, language: Language): void {
  for (const button of root.querySelectorAll<HTMLButtonElement>("[data-language-option]")) {
    const active = button.dataset.languageOption === language;
    button.setAttribute("aria-pressed", String(active));
    button.classList.toggle("language-option-active", active);
  }
}
